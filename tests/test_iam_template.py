"""IAM template tests: generator markers in place, and (opt-in) policy in sync with sraverify.

test_template_in_sync runs sra-verify's util/generate_iam_policy.py --check against
this repository's template. It needs a sra-verify checkout at the installed
sraverify version: set SRAVERIFY_REPO to its path.
"""

import os
import pytest
import re
import subprocess
import sys
from conftest import isolated_env
from importlib.metadata import version
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = REPO_ROOT / '1-sraverify-mcp-roles.yaml'

# Must match BEGIN_MARKER / END_MARKER in sra-verify's util/generate_iam_policy.py.
BEGIN_MARKER = (
    '# BEGIN GENERATED by util/generate_iam_policy.py -- do not edit; run it to regenerate'
)
END_MARKER = '# END GENERATED'


def test_template_has_generator_markers_and_check_permissions():
    text = TEMPLATE.read_text()
    lines = [line.strip() for line in text.splitlines()]
    assert lines.count(BEGIN_MARKER) == 1
    assert lines.count(END_MARKER) == 1
    assert lines.index(BEGIN_MARKER) < lines.index(END_MARKER)
    # The markers belong to SRAVerifyLeastPrivilege, after the check-permissions policy.
    assert text.index('SRAVerifyLeastPrivilege:') < text.index(BEGIN_MARKER)
    assert 'ManagedPolicyName: SRAVerifyMCPCheckPermissions' in text


@pytest.mark.skipif(
    not os.environ.get('SRAVERIFY_REPO'),
    reason='set SRAVERIFY_REPO to a sra-verify checkout to check IAM policy drift',
)
def test_template_in_sync():
    repo = Path(os.environ['SRAVERIFY_REPO']).resolve()
    init = (repo / 'sraverify' / 'sraverify' / '__init__.py').read_text()
    match = re.search(r'^__version__\s*=\s*[\'"]([^\'"]+)[\'"]', init, re.MULTILINE)
    assert match, f'no __version__ in {repo}/sraverify/sraverify/__init__.py'
    installed = version('sraverify')
    assert match.group(1) == installed, (
        f'SRAVERIFY_REPO is sraverify {match.group(1)} but {installed} is installed; '
        'check out the matching sra-verify version.'
    )

    proc = subprocess.run(
        [
            sys.executable,
            str(repo / 'util' / 'generate_iam_policy.py'),
            '--check',
            '--template',
            str(TEMPLATE),
        ],
        env=isolated_env(),
        capture_output=True,
        text=True,
        timeout=300,
    )
    assert proc.returncode == 0, (
        f'IAM policy drift (exit {proc.returncode}). Regenerate SRAVerifyLeastPrivilege by '
        f'running the generator without --check.\nstdout:\n{proc.stdout}\nstderr:\n{proc.stderr}'
    )
